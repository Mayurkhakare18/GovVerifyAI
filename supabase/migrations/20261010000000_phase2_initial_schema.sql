-- ==============================================================================
-- 6. ROW-LEVEL SECURITY POLICIES (SAFELY RERUNNABLE & RECURSION-FREE)
-- Uses DROP POLICY IF EXISTS before CREATE POLICY to guarantee idempotent execution.
-- RLS dependency graph is strictly a Directed Acyclic Graph (DAG) with zero self-joins.
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 6.1 Profiles Policies
-- Evaluates directly against auth.uid(). No table joins.
-- ------------------------------------------------------------------------------
DROP POLICY IF EXISTS "Users can view their own profile" ON public.profiles;
CREATE POLICY "Users can view their own profile"
  ON public.profiles
  FOR SELECT
  USING (auth.uid() = id);

DROP POLICY IF EXISTS "Users can insert their own profile" ON public.profiles;
CREATE POLICY "Users can insert their own profile"
  ON public.profiles
  FOR INSERT
  WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Users can update permitted fields on their own profile" ON public.profiles;
CREATE POLICY "Users can update permitted fields on their own profile"
  ON public.profiles
  FOR UPDATE
  USING (auth.uid() = id)
  WITH CHECK (auth.uid() = id);

-- ------------------------------------------------------------------------------
-- 6.2 Verification Requests Policies
-- Root of the verification hierarchy. Evaluates auth.uid() directly against user_id.
-- No joins to any other table.
-- ------------------------------------------------------------------------------
DROP POLICY IF EXISTS "Users can view their own verification requests" ON public.verification_requests;
CREATE POLICY "Users can view their own verification requests"
  ON public.verification_requests
  FOR SELECT
  USING (auth.uid() IS NOT NULL AND auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can create verification requests" ON public.verification_requests;
CREATE POLICY "Users can create verification requests"
  ON public.verification_requests
  FOR INSERT
  WITH CHECK (auth.uid() IS NOT NULL AND auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update their own verification requests" ON public.verification_requests;

DROP POLICY IF EXISTS "Users can delete their own verification requests" ON public.verification_requests;
CREATE POLICY "Users can delete their own verification requests"
  ON public.verification_requests
  FOR DELETE
  USING (auth.uid() IS NOT NULL AND auth.uid() = user_id);

-- ------------------------------------------------------------------------------
-- 6.3 Claims Policies
-- Evaluates verification_request_id against verification_requests(user_id = auth.uid()).
-- Forward check only. Zero recursion.
-- ------------------------------------------------------------------------------
DROP POLICY IF EXISTS "Users can view claims linked to their own requests" ON public.claims;
CREATE POLICY "Users can view claims linked to their own requests"
  ON public.claims
  FOR SELECT
  USING (
    auth.uid() IS NOT NULL AND
    EXISTS (
      SELECT 1 FROM public.verification_requests vr
      WHERE vr.id = claims.verification_request_id
        AND vr.user_id = auth.uid()
    )
  );

DROP POLICY IF EXISTS "Users can insert claims linked to their own requests" ON public.claims;
DROP POLICY IF EXISTS "Users can delete claims linked to their own requests" ON public.claims;

-- ------------------------------------------------------------------------------
-- 6.4 Evidence Policies (CORRECTED: RECURSION REMOVED)
-- Previously checked public.evidence e2 (self-referencing subquery), risking recursion.
-- Now directly joins verification_request_id to verification_requests(user_id = auth.uid()).
-- Forward check only. Zero recursion.
-- ------------------------------------------------------------------------------
DROP POLICY IF EXISTS "Users can view evidence linked to their own requests" ON public.evidence;
CREATE POLICY "Users can view evidence linked to their own requests"
  ON public.evidence
  FOR SELECT
  USING (
    auth.uid() IS NOT NULL AND
    EXISTS (
      SELECT 1 FROM public.verification_requests vr
      WHERE vr.id = evidence.verification_request_id
        AND vr.user_id = auth.uid()
    )
  );

DROP POLICY IF EXISTS "Users can insert evidence linked to their own requests" ON public.evidence;
DROP POLICY IF EXISTS "Users can delete evidence linked to their own requests" ON public.evidence;

-- ------------------------------------------------------------------------------
-- 6.5 Sources Policies
-- Reads sources backing evidence belonging to the user's verification requests.
-- Subquery joins evidence -> verification_requests. Since verification_requests
-- has zero RLS subqueries, this cannot form a cycle.
-- ------------------------------------------------------------------------------
DROP POLICY IF EXISTS "Users can view sources linked to their evidence" ON public.sources;
CREATE POLICY "Users can view sources linked to their evidence"
  ON public.sources
  FOR SELECT
  USING (
    auth.uid() IS NOT NULL AND
    EXISTS (
      SELECT 1 FROM public.evidence e
      JOIN public.verification_requests vr ON vr.id = e.verification_request_id
      WHERE e.source_id = sources.id
        AND vr.user_id = auth.uid()
    )
  );

DROP POLICY IF EXISTS "Authenticated users can insert sources" ON public.sources;

-- ------------------------------------------------------------------------------
-- 6.6 Verification Results Policies
-- Direct forward check from verification_request_id to verification_requests.
-- Zero recursion.
-- ------------------------------------------------------------------------------
DROP POLICY IF EXISTS "Users can view verification results for their own requests" ON public.verification_results;
CREATE POLICY "Users can view verification results for their own requests"
  ON public.verification_results
  FOR SELECT
  USING (
    auth.uid() IS NOT NULL AND
    EXISTS (
      SELECT 1 FROM public.verification_requests vr
      WHERE vr.id = verification_results.verification_request_id
        AND vr.user_id = auth.uid()
    )
  );

DROP POLICY IF EXISTS "Users can insert verification results" ON public.verification_results;
DROP POLICY IF EXISTS "Users can update verification results" ON public.verification_results;
DROP POLICY IF EXISTS "Users can delete verification results" ON public.verification_results;
