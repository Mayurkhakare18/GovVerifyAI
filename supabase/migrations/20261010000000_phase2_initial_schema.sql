-- 3.2 Helper Functions (with secure search_path to prevent search-path hijacking)
CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

-- Trigger function for automatic profile initialization upon Supabase auth sign-up
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
BEGIN
  INSERT INTO public.profiles (id, display_name, preferred_language)
  VALUES (
    NEW.id,
    COALESCE(
      NEW.raw_user_meta_data->>'display_name',
      NEW.raw_user_meta_data->>'full_name',
      SPLIT_PART(NEW.email, '@', 1)
    ),
    COALESCE(NEW.raw_user_meta_data->>'preferred_language', 'English')
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;

-- Restrict function execution: Only postgres / auth triggers can run handle_new_user
REVOKE EXECUTE ON FUNCTION public.handle_new_user() FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.handle_new_user() FROM anon;
REVOKE EXECUTE ON FUNCTION public.handle_new_user() FROM authenticated;
GRANT EXECUTE ON FUNCTION public.handle_new_user() TO service_role;
GRANT EXECUTE ON FUNCTION public.handle_new_user() TO supabase_auth_admin;

-- 3.3 Triggers
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

DROP TRIGGER IF EXISTS set_profiles_updated_at ON public.profiles;
CREATE TRIGGER set_profiles_updated_at
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

DROP TRIGGER IF EXISTS set_verification_requests_updated_at ON public.verification_requests;
CREATE TRIGGER set_verification_requests_updated_at
  BEFORE UPDATE ON public.verification_requests
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

-- ==============================================================================
-- 4. TABLE & COLUMN LEVEL PRIVILEGES (DEFENSE-IN-DEPTH AUDIT)
-- Restrict client roles (anon, authenticated) at the SQL permission boundary.
-- Pipeline data tables cannot be inserted, updated, or deleted by client roles.
-- ==============================================================================

-- 4.1 Profiles permissions:
-- Authenticated users can SELECT and INSERT their own profile, and UPDATE only permitted columns.
GRANT SELECT, INSERT ON public.profiles TO authenticated;
GRANT UPDATE (display_name, preferred_language) ON public.profiles TO authenticated;
REVOKE UPDATE (id, created_at, updated_at) ON public.profiles FROM authenticated;
REVOKE ALL ON public.profiles FROM anon;

-- 4.2 Verification Requests permissions:
-- Authenticated users can SELECT, INSERT, and DELETE their own requests.
-- Mutation of status or results is blocked from clients.
GRANT SELECT, INSERT, DELETE ON public.verification_requests TO authenticated;
REVOKE UPDATE ON public.verification_requests FROM authenticated;
REVOKE ALL ON public.verification_requests FROM anon;

-- 4.3 Pipeline Tables (claims, sources, evidence, verification_results):
-- Pure read-only for authenticated clients (governed further by RLS).
-- INSERT, UPDATE, and DELETE are strictly REVOKED from anon and authenticated.
GRANT SELECT ON public.claims TO authenticated;
REVOKE INSERT, UPDATE, DELETE ON public.claims FROM authenticated, anon;

GRANT SELECT ON public.sources TO authenticated;
REVOKE INSERT, UPDATE, DELETE ON public.sources FROM authenticated, anon;

GRANT SELECT ON public.evidence TO authenticated;
REVOKE INSERT, UPDATE, DELETE ON public.evidence FROM authenticated, anon;

GRANT SELECT ON public.verification_results TO authenticated;
REVOKE INSERT, UPDATE, DELETE ON public.verification_results FROM authenticated, anon;

-- Anon has zero direct table access to any public table
REVOKE ALL ON public.claims FROM anon;
REVOKE ALL ON public.sources FROM anon;
REVOKE ALL ON public.evidence FROM anon;
REVOKE ALL ON public.verification_results FROM anon;

