-- Migration: 20261010000000_phase2_initial_schema.sql
-- Description: Core tables, constraints, foreign keys, indexes, triggers,
--              explicit GRANT/REVOKE privileges, and non-recursive RLS policies.
--
-- Security Model & Architecture:
-- 1. Dependency Ordering:
--    - Prerequisites and extensions created first.
--    - All six core tables created before any indexes, triggers, or RLS policies.
--    - Foreign keys, indexes, helper functions, and triggers created in order.
--    - Row-Level Security enabled and configured after all tables exist.
-- 2. Non-Recursive RLS Dependency Graph:
--    - RLS evaluation flows strictly in one direction (DAG - Directed Acyclic Graph):
--      * public.profiles: Evaluates auth.uid() = id directly (Zero joins).
--      * public.verification_requests: Evaluates auth.uid() = user_id directly (Zero joins).
--      * public.claims: Checks verification_requests(user_id = auth.uid()) (1 forward join).
--      * public.evidence: Checks verification_requests(user_id = auth.uid()) directly via
--        verification_request_id (1 forward join, NO self-referencing subqueries).
--      * public.verification_results: Checks verification_requests(user_id = auth.uid()) (1 forward join).
--      * public.sources: Checks evidence -> verification_requests(user_id = auth.uid()) (Strict downward join).
--      * NO cycle exists: verification_requests never queries evidence or claims.
-- 3. Server-Authoritative Pipeline Isolation (Table & Column Level Grants):
--    - Pipeline tables (sources, evidence, verification_results, claims) are WRITTEN
--      EXCLUSIVELY through the trusted Express backend using SUPABASE_SECRET_KEY (service_role).
--    - INSERT, UPDATE, and DELETE privileges are explicitly REVOKED on pipeline tables from
--      anon and authenticated client roles.
--    - Direct client UPDATE on public.profiles is limited strictly to user-editable fields
--      (display_name, preferred_language). Direct UPDATE on id, created_at is REVOKED.
-- 4. Guest Request Authorization:
--    - guest_session_token (TEXT) stores a cryptographically secure token generated by the server.
--    - Anonymous/guest callers must supply this token in X-Guest-Token to retrieve results.
-- 5. Safe Rerun Idempotency:
--    - Uses IF NOT EXISTS, CREATE OR REPLACE, and DROP POLICY IF EXISTS so this script
--      can be re-executed cleanly without duplicate policy or duplicate object errors.
-- ==============================================================================

-- ==============================================================================
-- 1. EXTENSIONS & PREREQUISITES
-- ==============================================================================
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ==============================================================================
-- 2. CORE TABLES (CREATED IN STRICT DEPENDENCY ORDER)
-- ==============================================================================

-- 2.1 Profiles Table (references auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  display_name TEXT,
  preferred_language TEXT NOT NULL DEFAULT 'English',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2.2 Verification Requests Table
-- user_id references auth.users (nullable for server-mediated guest intake).
-- guest_session_token stores a secure server-generated token to protect guest records.
CREATE TABLE IF NOT EXISTS public.verification_requests (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  guest_session_token TEXT,
  input_type TEXT NOT NULL CHECK (input_type IN ('CLAIM', 'DOCUMENT')),
  original_claim TEXT,
  status TEXT NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED', 'PROCESSING', 'COMPLETED', 'FAILED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2.3 Claims Table (references verification_requests)
CREATE TABLE IF NOT EXISTS public.claims (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  verification_request_id UUID NOT NULL REFERENCES public.verification_requests(id) ON DELETE CASCADE,
  claim_text TEXT NOT NULL,
  claim_type TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2.4 Sources Table (standalone reference table for sovereign government sources)
CREATE TABLE IF NOT EXISTS public.sources (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  title TEXT NOT NULL,
  url TEXT NOT NULL,
  domain TEXT NOT NULL,
  issuing_authority TEXT,
  source_type TEXT,
  publication_date TEXT,
  retrieved_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2.5 Evidence Table (references verification_requests, claims, sources)
CREATE TABLE IF NOT EXISTS public.evidence (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  verification_request_id UUID NOT NULL REFERENCES public.verification_requests(id) ON DELETE CASCADE,
  claim_id UUID REFERENCES public.claims(id) ON DELETE SET NULL,
  source_id UUID NOT NULL REFERENCES public.sources(id) ON DELETE CASCADE,
  extracted_text TEXT NOT NULL,
  page_number INTEGER,
  clause_reference TEXT,
  relationship TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2.6 Verification Results Table (references verification_requests)
CREATE TABLE IF NOT EXISTS public.verification_results (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  verification_request_id UUID NOT NULL UNIQUE REFERENCES public.verification_requests(id) ON DELETE CASCADE,
  verdict TEXT CHECK (verdict IN ('SUPPORTED', 'PARTIALLY_SUPPORTED', 'CONTRADICTED', 'INSUFFICIENT_EVIDENCE')),
  confidence NUMERIC CHECK (confidence >= 0 AND confidence <= 100),
  explanation TEXT,
  completed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

